/// A pill (rounded rect + vertically centred label) whose right edge sits at `right`.
func pill(_ text: String, _ f: CTFont, right: CGFloat, top: CGFloat, height: CGFloat,
          padding: CGFloat, radius: CGFloat, fill: String, textFill: String) -> (svg: String, width: CGFloat) {
    let o = outline(text, f)
    let w = o.width + padding * 2
    let x = right - w
    let baseline = top + (height - (CTFontGetAscent(f) + CTFontGetDescent(f))) / 2 + CTFontGetAscent(f)
    let s = """
      <rect x="\(n(x))" y="\(n(top))" width="\(n(w))" height="\(n(height))" rx="\(n(radius))" fill="\(fill)"/>
      <path transform="translate(\(n(x + padding)) \(n(baseline)))" d="\(o.d)" fill="\(textFill)"/>
    """
    return (s, w)
}

