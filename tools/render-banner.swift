// Renders docs/assets/banner.svg. Every string is converted to outlines, so the banner
// renders identically everywhere — GitHub serves README SVGs as <img>, which loads no
// external fonts, and embedding the two TTFs as base64 would cost ~1.8MB.
//
//   swift tools/render-banner.swift
//
// The faces are the product's own, read straight out of the module that ships them to the app
// (`presentation-core-styling/src/main/composeResources/font/`) — the same two the docs site
// pulls from Google Fonts. Both are variable, so a weight is an axis value, not another file.

let fontDir = "presentation-core-styling/src/main/composeResources/font"

let wghtAxis = 0x77676874  // 'wght'
let opszAxis = 0x6F70737A  // 'opsz' — Roboto Flex only; CoreText will not guess it for us

func font(_ file: String, _ size: CGFloat, weight: CGFloat, opticalSize: CGFloat? = nil) -> CTFont {
    let url = URL(fileURLWithPath: "\(fontDir)/\(file)")
    guard let provider = CGDataProvider(url: url as CFURL), let cg = CGFont(provider) else {
        FileHandle.standardError.write("missing font: \(url.path)\n".data(using: .utf8)!)
        exit(2)
    }
    let base = CTFontCreateWithGraphicsFont(cg, size, nil, nil)
    var axes: [Int: CGFloat] = [wghtAxis: weight]
    if let opticalSize { axes[opszAxis] = opticalSize }
    let descriptor = CTFontDescriptorCreateWithAttributes(
        [kCTFontVariationAttribute: axes] as CFDictionary)
    return CTFontCreateCopyWithAttributes(base, size, nil, descriptor)
}

struct Outline { let width: CGFloat; let d: String }

/// Glyph outlines for `text`, baseline at y=0, growing to the right, in SVG (y-down) space.
func outline(_ text: String, _ ctFont: CTFont) -> Outline {
    let line = CTLineCreateWithAttributedString(
        NSAttributedString(string: text, attributes: [.font: ctFont]))
    let width = CGFloat(CTLineGetTypographicBounds(line, nil, nil, nil))
    var d = ""
    func n(_ v: CGFloat) -> String { String(format: "%.2f", v) }

    for run in (CTLineGetGlyphRuns(line) as! [CTRun]) {
        let count = CTRunGetGlyphCount(run)
        var glyphs = [CGGlyph](repeating: 0, count: count)
        var points = [CGPoint](repeating: .zero, count: count)
        CTRunGetGlyphs(run, CFRangeMake(0, count), &glyphs)
        CTRunGetPositions(run, CFRangeMake(0, count), &points)
        let runFont = (CTRunGetAttributes(run) as NSDictionary)[kCTFontAttributeName] as! CTFont

        for i in 0..<count {
            var t = CGAffineTransform(scaleX: 1, y: -1)
                .concatenating(CGAffineTransform(translationX: points[i].x, y: 0))
            guard let path = CTFontCreatePathForGlyph(runFont, glyphs[i], &t) else { continue }
            path.applyWithBlock { e in
                let p = e.pointee.points
                switch e.pointee.type {
                case .moveToPoint:         d += "M\(n(p[0].x)) \(n(p[0].y))"
                case .addLineToPoint:      d += "L\(n(p[0].x)) \(n(p[0].y))"
                case .addQuadCurveToPoint: d += "Q\(n(p[0].x)) \(n(p[0].y)) \(n(p[1].x)) \(n(p[1].y))"
                case .addCurveToPoint:     d += "C\(n(p[0].x)) \(n(p[0].y)) \(n(p[1].x)) \(n(p[1].y)) \(n(p[2].x)) \(n(p[2].y))"
                case .closeSubpath:        d += "Z"
                @unknown default: break
                }
            }
        }
    }
    return Outline(width: width, d: d)
}

func n(_ v: CGFloat) -> String { String(format: "%.2f", v) }

/// `text` as a `<path>`, right edge pinned to `right`, baseline at `baseline`.
func rightAligned(_ text: String, _ f: CTFont, right: CGFloat, baseline: CGFloat, fill: String) -> String {
    let o = outline(text, f)
    return "  <path transform=\"translate(\(n(right - o.width)) \(n(baseline)))\" d=\"\(o.d)\" fill=\"\(fill)\"/>"
}

